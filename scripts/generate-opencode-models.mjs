// Generate the static OpenCode Go model table used by the adapter's fallback
// catalog. Source: @earendil-works/pi-ai provider data (models.dev), snapshot
// 2026-10-24. Run: node scripts/generate-opencode-models.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const source = JSON.parse(readFileSync('data/opencode-go.json', 'utf8'))
const models = []
for (const [api, entries] of Object.entries(source)) {
  for (const [id, m] of Object.entries(entries)) {
    models.push({
      id,
      name: typeof m.name === 'string' && m.name.length > 0 ? m.name : id,
      api,
      reasoning: m.reasoning === true,
      input: Array.isArray(m.input) ? m.input : ['text'],
      ...m.contextWindow === undefined ? {} : { contextWindow: m.contextWindow },
      ...m.maxTokens === undefined ? {} : { maxTokens: m.maxTokens },
      ...m.thinkingLevelMap === undefined ? {} : { thinkingLevelMap: m.thinkingLevelMap },
      ...m.compat?.thinkingFormat === undefined ? {} : { thinkingFormat: m.compat.thinkingFormat },
      ...m.compat?.supportsReasoningEffort === undefined ? {} : { supportsReasoningEffort: m.compat.supportsReasoningEffort },
    })
  }
}
models.sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id))
const lines = []
lines.push('/**')
lines.push(' * Static OpenCode Go model catalog (fallback when live discovery fails).')
lines.push(' *')
lines.push(' * Generated by `scripts/generate-opencode-models.mjs` from')
lines.push(' * `data/opencode-go.json` (snapshot of @earendil-works/pi-ai provider data /')
lines.push(' * models.dev, 2026-10-24). Do not edit by hand.')
lines.push(' */')
lines.push('')
lines.push("export type OpencodeWire = 'openai-completions' | 'openai-responses' | 'anthropic-messages'")
lines.push('')
lines.push('/** One catalog entry, as far as this adapter needs it. */')
lines.push('export interface OpencodeModelMeta {')
lines.push('  id: string')
lines.push('  name: string')
lines.push('  api: OpencodeWire')
lines.push('  reasoning: boolean')
lines.push("  input: ('text' | 'image')[]")
lines.push('  contextWindow?: number')
lines.push('  maxTokens?: number')
lines.push('  thinkingLevelMap?: Record<string, string | null>')
lines.push("  thinkingFormat?: 'deepseek' | 'qwen'")
lines.push('  supportsReasoningEffort?: boolean')
lines.push('}')
lines.push('')
lines.push('/** Every built-in OpenCode Go model, alphabetical by display name. */')
lines.push('export const OPENCODE_MODELS: readonly OpencodeModelMeta[] = [')
for (const m of models) {
  lines.push('  ' + JSON.stringify(m) + ',')
}
lines.push(']')
lines.push('')
lines.push('/** Index by wire model id. */')
lines.push('export const OPENCODE_MODEL_BY_ID: ReadonlyMap<string, OpencodeModelMeta> = new Map(')
lines.push('  OPENCODE_MODELS.map(model => [model.id, model]),')
lines.push(')')
lines.push('')
writeFileSync('src/providers/opencode-models.ts', lines.join('\n'))
console.log('generated', models.length, 'models')
